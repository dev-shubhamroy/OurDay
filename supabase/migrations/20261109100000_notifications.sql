-- OurDay · Notification system (additive: new tables and functions only; no existing table is altered).
--
--   notification_preferences  one row per person: master / deadlines / habits / partner / unlock_briefing + timezone.
--   notifications             per-person history with read/unread state, referencing the task or habit.
--
-- Rows in `notifications` are created ONLY by SECURITY DEFINER code (the generator and the partner triggers),
-- never by clients. A person can read their own rows and change only `read_at`. Everything is scoped to the
-- person's own workspace, so nothing from another workspace can appear.
--
-- Deadline reminders and the 9:30 PM habit check-in are generated by `generate_notifications_for`, which is
--   * called by pg_cron every minute when that extension is available (best effort, see the bottom), and
--   * callable by a signed-in client for THEMSELVES (`generate_my_notifications`), so history is complete even
--     if cron is unavailable. It is idempotent: a unique (user_id, dedupe_key) makes duplicates impossible.
-- OS-level alerts on the Mac are scheduled natively by the companion; this table is the shared record.

create table public.notification_preferences (
  user_id         uuid primary key references public.profiles (id) on delete cascade,
  master          boolean not null default true,
  deadlines       boolean not null default true,
  habits          boolean not null default true,
  partner         boolean not null default true,
  unlock_briefing boolean not null default true,
  -- IANA name, kept current by the person's devices; used for the 9:30 PM check-in and clock text.
  timezone        text not null default 'UTC' check (char_length(timezone) between 1 and 64),
  updated_at      timestamptz not null default now()
);

create trigger notification_preferences_set_updated_at
  before update on public.notification_preferences
  for each row execute function public.set_updated_at();

create table public.notifications (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references public.profiles (id) on delete cascade,
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  kind         text not null check (kind in ('deadline', 'habit', 'partner')),
  title        text not null check (char_length(title) between 1 and 200),
  body         text not null check (char_length(body) <= 600),
  task_id      uuid references public.tasks (id) on delete set null,
  habit_id     uuid references public.habits (id) on delete set null,
  actor_id     uuid references public.profiles (id) on delete set null,
  dedupe_key   text not null check (char_length(dedupe_key) <= 200),
  -- When the reminder was due / the event happened (not when the row was inserted).
  occurred_at  timestamptz not null default now(),
  read_at      timestamptz,
  created_at   timestamptz not null default now(),
  constraint notifications_unique_event unique (user_id, dedupe_key)
);

create index notifications_user_time_idx   on public.notifications (user_id, occurred_at desc);
create index notifications_user_unread_idx on public.notifications (user_id) where read_at is null;

-- ---------------------------------------------------------------------------
-- Row Level Security and grants
-- ---------------------------------------------------------------------------
alter table public.notification_preferences enable row level security;
alter table public.notifications             enable row level security;

revoke all on table public.notification_preferences, public.notifications from public, anon, authenticated;
grant select, insert, update on public.notification_preferences to authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;   -- the ONLY column a client may change

create policy notification_preferences_select on public.notification_preferences for select to authenticated
  using (user_id = (select auth.uid()));
create policy notification_preferences_insert on public.notification_preferences for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy notification_preferences_update on public.notification_preferences for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy notifications_select on public.notifications for select to authenticated
  using (user_id = (select auth.uid()));
create policy notifications_update on public.notifications for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Helpers (not callable by clients)
-- ---------------------------------------------------------------------------
create or replace function public.notif_tz(p_user uuid)
returns text language sql stable security definer set search_path = '' as $$
  select coalesce((select z.name from public.notification_preferences p
                   join pg_catalog.pg_timezone_names z on z.name = p.timezone where p.user_id = p_user), 'UTC')
$$;

-- The other member of this person's workspace, or null.
create or replace function public.notif_other_member(p_workspace uuid, p_user uuid)
returns uuid language sql stable security definer set search_path = '' as $$
  select m.user_id from public.workspace_members m where m.workspace_id = p_workspace and m.user_id <> p_user limit 1
$$;

create or replace function public.notif_pref(p_user uuid, p_key text)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select case p_key
              when 'deadlines' then p.master and p.deadlines
              when 'habits'    then p.master and p.habits
              when 'partner'   then p.master and p.partner
              else p.master end
       from public.notification_preferences p where p.user_id = p_user), true)
$$;

create or replace function public.notif_first_name(p_user uuid)
returns text language sql stable security definer set search_path = '' as $$
  select coalesce(nullif(split_part((select name from public.profiles where id = p_user), ' ', 1), ''), 'Your partner')
$$;

-- ---------------------------------------------------------------------------
-- Generator: deadline reminders + 9:30 PM habit check-in for ONE person (their own workspace only)
-- ---------------------------------------------------------------------------
create or replace function public.generate_notifications_for(p_user uuid, p_now timestamptz default now())
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  ws uuid;
  tz text;
  n int := 0;
  c int;
  local_now timestamp;
  local_day date;
begin
  select m.workspace_id into ws from public.workspace_members m where m.user_id = p_user limit 1;
  if ws is null or not public.notif_pref(p_user, 'master') then return 0; end if;
  tz := public.notif_tz(p_user);

  -- Deadline reminders: 24h, 12h, 6h, 3h, 2h, 1h, 30m, 15m, 5m and the exact deadline.
  -- Only intervals that came due within the last 30 minutes are created (no back-filling after a long gap),
  -- only for OPEN deadlines, and no reminder is created once the deadline has passed (except the exact one).
  if public.notif_pref(p_user, 'deadlines') then
    insert into public.notifications (user_id, workspace_id, kind, title, body, task_id, actor_id, dedupe_key, occurred_at)
    select p_user, ws, 'deadline',
           case when iv.secs = 0 then 'Deadline now' else 'Due in ' || iv.label end,
           '“' || t.title || '”'
             || case when t.created_by <> p_user then ' (' || public.notif_first_name(t.created_by) || '’s)' else '' end
             || case when iv.secs = 0 then ' is due now.'
                     else ' is due at ' || to_char(t.due_at at time zone tz, 'FMHH12:MI AM') || '.' end,
           t.id, t.created_by,
           'dl:' || t.id || ':' || extract(epoch from t.due_at)::bigint || ':' || iv.secs,
           t.due_at - make_interval(secs => iv.secs)
    from public.tasks t
    cross join (values (86400, '24 hours'), (43200, '12 hours'), (21600, '6 hours'), (10800, '3 hours'), (7200, '2 hours'),
                       (3600, '1 hour'), (1800, '30 minutes'), (900, '15 minutes'), (300, '5 minutes'), (0, '')) as iv (secs, label)
    where t.workspace_id = ws and t.kind = 'deadline' and t.status = 'open' and t.due_at is not null
      and (t.created_by = p_user or t.notify_second_user)
      and t.due_at - make_interval(secs => iv.secs) <= p_now
      and t.due_at - make_interval(secs => iv.secs) > p_now - interval '30 minutes'
      and (iv.secs = 0 or t.due_at > p_now)
    on conflict (user_id, dedupe_key) do nothing;
    get diagnostics c = row_count; n := n + c;
  end if;

  -- Habit check-in at 9:30 PM in the person's timezone: scheduled, unpaused, started, theirs, not yet logged.
  if public.notif_pref(p_user, 'habits') then
    local_now := p_now at time zone tz;
    local_day := local_now::date;
    if local_now::time >= time '21:30' then
      insert into public.notifications (user_id, workspace_id, kind, title, body, habit_id, dedupe_key, occurred_at)
      select p_user, ws, 'habit', 'Habit check-in', 'Did you complete “' || h.title || '” today?', h.id,
             'hb:' || h.id || ':' || local_day, (local_day + time '21:30') at time zone tz
      from public.habits h
      where h.workspace_id = ws and not h.paused and h.start_date <= local_day
        and (h.schedule_days is null or extract(dow from local_day)::smallint = any (h.schedule_days))
        and ((h.is_shared and exists (select 1 from public.workspace_members m where m.workspace_id = ws and m.user_id = p_user))
             or (not h.is_shared and h.owner_id = p_user))
        and not exists (select 1 from public.habit_logs l where l.habit_id = h.id and l.user_id = p_user and l.day = local_day)
      on conflict (user_id, dedupe_key) do nothing;
      get diagnostics c = row_count; n := n + c;
    end if;
  end if;
  return n;
end;
$$;

-- A signed-in person generates ONLY their own notifications.
create or replace function public.generate_my_notifications()
returns integer language plpgsql security definer set search_path = '' as $$
declare uid uuid := (select auth.uid());
begin
  if uid is null then raise exception 'not_authenticated' using errcode = '28000'; end if;
  return public.generate_notifications_for(uid, now());
end $$;

-- Cron entry point: everyone, plus housekeeping (history older than 90 days is dropped).
create or replace function public.generate_all_notifications()
returns integer language plpgsql security definer set search_path = '' as $$
declare r record; n int := 0;
begin
  for r in select distinct user_id from public.workspace_members loop
    n := n + public.generate_notifications_for(r.user_id, now());
  end loop;
  delete from public.notifications where created_at < now() - interval '90 days';
  return n;
end $$;

-- ---------------------------------------------------------------------------
-- Partner activity (created by triggers, so it works whichever device acted)
-- ---------------------------------------------------------------------------
-- Rule: the OTHER member is told when (a) their own task is completed, (b) a task/habit shared with them via
-- "Notify second user" is completed / checked in / newly shared, or (c) a shared habit is checked in.
-- The recipient's own preferences (master + partner) are honoured. Never crosses workspaces.
create or replace function public.notify_partner_task()
returns trigger language plpgsql security definer set search_path = '' as $$
declare actor uuid; rcpt uuid; kind_word text;
begin
  kind_word := case new.kind when 'deadline' then 'deadline' else 'task' end;
  if tg_op = 'INSERT' then
    actor := new.created_by;
    rcpt := public.notif_other_member(new.workspace_id, actor);
    if rcpt is null or not new.notify_second_user or not public.notif_pref(rcpt, 'partner') then return new; end if;
    insert into public.notifications (user_id, workspace_id, kind, title, body, task_id, actor_id, dedupe_key, occurred_at)
    values (rcpt, new.workspace_id, 'partner', public.notif_first_name(actor) || ' shared a ' || kind_word || ' with you',
            '“' || new.title || '”', new.id, actor, 'pa:task:' || new.id || ':new', now())
    on conflict (user_id, dedupe_key) do nothing;
  elsif new.status = 'completed' and old.status = 'open' then
    actor := new.completed_by;
    if actor is null then return new; end if;
    rcpt := public.notif_other_member(new.workspace_id, actor);
    if rcpt is null or not public.notif_pref(rcpt, 'partner') then return new; end if;
    if new.created_by = rcpt or (new.created_by = actor and new.notify_second_user) then
      insert into public.notifications (user_id, workspace_id, kind, title, body, task_id, actor_id, dedupe_key, occurred_at)
      values (rcpt, new.workspace_id, 'partner', public.notif_first_name(actor) || ' completed a ' || kind_word,
              '“' || new.title || '”', new.id, actor, 'pa:task:' || new.id || ':completed:' || extract(epoch from new.completed_at)::bigint, now())
      on conflict (user_id, dedupe_key) do nothing;
    end if;
  end if;
  return new;
end $$;

create trigger notify_partner_task_ins after insert on public.tasks
  for each row execute function public.notify_partner_task();
create trigger notify_partner_task_upd after update of status on public.tasks
  for each row execute function public.notify_partner_task();

create or replace function public.notify_partner_habit()
returns trigger language plpgsql security definer set search_path = '' as $$
declare h public.habits%rowtype; rcpt uuid;
begin
  if new.status <> 'done' or (tg_op = 'UPDATE' and old.status = 'done') then return new; end if;
  select * into h from public.habits where id = new.habit_id;
  if not found then return new; end if;
  rcpt := public.notif_other_member(h.workspace_id, new.user_id);
  if rcpt is null or not public.notif_pref(rcpt, 'partner') then return new; end if;
  if h.is_shared or h.notify_second_user then
    insert into public.notifications (user_id, workspace_id, kind, title, body, habit_id, actor_id, dedupe_key, occurred_at)
    values (rcpt, h.workspace_id, 'partner', public.notif_first_name(new.user_id) || ' checked in a habit',
            '“' || h.title || '”', h.id, new.user_id, 'pa:habit:' || h.id || ':' || new.user_id || ':' || new.day, now())
    on conflict (user_id, dedupe_key) do nothing;
  end if;
  return new;
end $$;

create trigger notify_partner_habit_ins after insert on public.habit_logs
  for each row execute function public.notify_partner_habit();
create trigger notify_partner_habit_upd after update of status on public.habit_logs
  for each row execute function public.notify_partner_habit();

-- ---------------------------------------------------------------------------
-- Function privileges: trigger/helper/cron functions are never callable by clients.
-- ---------------------------------------------------------------------------
revoke all on function public.notif_tz(uuid), public.notif_other_member(uuid, uuid), public.notif_pref(uuid, text),
  public.notif_first_name(uuid), public.generate_notifications_for(uuid, timestamptz), public.generate_all_notifications(),
  public.notify_partner_task(), public.notify_partner_habit() from public, anon, authenticated;
revoke all on function public.generate_my_notifications() from public, anon;
grant execute on function public.generate_my_notifications() to authenticated;

-- ---------------------------------------------------------------------------
-- Realtime (so the web app and Mac can refresh promptly) and cron (best effort)
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notifications') then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;

-- Backend scheduler: every minute. If pg_cron is not available the migration still succeeds and clients
-- call generate_my_notifications() instead (the Mac companion every 2 minutes, the web app while open).
do $$
begin
  create extension if not exists pg_cron;
  perform cron.schedule('ourday-generate-notifications', '* * * * *', 'select public.generate_all_notifications()');
exception when others then
  raise notice 'pg_cron not enabled (%); notifications are generated by client calls only', sqlerrm;
end $$;
